def _norm_p3(val):
    s = str(val or "").strip()
    if s.endswith(".0"):
        s = s[:-2]
    return s


def _rank_from_total(total):
    if total >= 9.0:
        return "Xuất sắc"
    if total >= 8.0:
        return "Giỏi"
    if total >= 6.5:
        return "Khá"
    if total >= 5.0:
        return "Trung bình"
    if total >= 3.5:
        return "Yếu"
    return "Kém"


def _compute_student_fields(s):
    key = MASTER_KEYS[str(s["code"])]

    # Phần I (3.00đ)
    p1_wrong = []
    p1_ok = 0
    for idx in range(12):
        ans_s = s["answers_p1"][idx] if idx < len(s["answers_p1"]) else ""
        ans_k = key["p1"][idx]
        if ans_s == ans_k:
            p1_ok += 1
        else:
            p1_wrong.append(f"C{idx+1}({ans_s or 'Trống'}→{ans_k})")
    p1 = round(0.25 * p1_ok, 2)

    # Phần II (2.00đ - thang chuẩn Bộ GD&ĐT: 0.10 / 0.25 / 0.50 / 1.00 mỗi câu)
    key_13 = key["p2_13"]
    key_14 = key["p2_14"]
    sub_names = ["a", "b", "c", "d"]
    p2_wrong = []
    c13_ok = 0
    for i in range(4):
        ans_s = s["answers_p2"][i] if i < len(s["answers_p2"]) else ""
        if ans_s == key_13[i]:
            c13_ok += 1
        else:
            p2_wrong.append(f"13{sub_names[i]}({ans_s or 'Trống'}→{key_13[i]})")
    c14_ok = 0
    for i in range(4):
        ans_s = s["answers_p2"][4 + i] if (4 + i) < len(s["answers_p2"]) else ""
        if ans_s == key_14[i]:
            c14_ok += 1
        else:
            p2_wrong.append(f"14{sub_names[i]}({ans_s or 'Trống'}→{key_14[i]})")
    c13_pts = P2_SCALE[c13_ok]
    c14_pts = P2_SCALE[c14_ok]
    p2 = round(c13_pts + c14_pts, 2)

    # Phần III (2.00đ - 0.50đ mỗi câu)
    p3_ok = 0
    p3_wrong = []
    for i in range(4):
        ans_s = _norm_p3(s["answers_p3"][i] if i < len(s["answers_p3"]) else "")
        ans_k = _norm_p3(key["p3"][i])
        if ans_s == ans_k:
            p3_ok += 1
        else:
            p3_wrong.append(f"C{15+i}({ans_s or 'Trống'}→{ans_k})")
    p3 = round(0.50 * p3_ok, 2)

    # Phần IV (3.00đ)
    p4_det = s["p4_detail"]
    c19 = round(0.25 * sum(1 for st in p4_det["C19"]["steps"] if st["ok"]), 2)
    c20 = round(0.25 * sum(1 for st in p4_det["C20"]["steps"] if st["ok"]), 2)
    c21 = round(0.25 * sum(1 for st in p4_det["C21"]["steps"] if st["ok"]), 2)
    assert abs(c19 - p4_det["C19"]["score"]) < 1e-6, f"STT {s['stt']} C19 step mismatch"
    assert abs(c20 - p4_det["C20"]["score"]) < 1e-6, f"STT {s['stt']} C20 step mismatch"
    assert abs(c21 - p4_det["C21"]["score"]) < 1e-6, f"STT {s['stt']} C21 step mismatch"
    answers_p4 = [c19, c20, c21]
    p4 = round(sum(answers_p4), 2)

    total_tn = round(p1 + p2 + p3, 2)
    total = round(total_tn + p4, 2)
    rank = _rank_from_total(total)

    s["p1"] = p1
    s["p2"] = p2
    s["p2_c13"] = c13_pts
    s["p2_c14"] = c14_pts
    s["p3"] = p3
    s["p4"] = p4
    s["answers_p4"] = answers_p4
    s["total_tn"] = total_tn
    s["total"] = total
    s["scale10"] = total
    s["rank"] = rank

    s["details_p1"] = f"{p1_ok}/12 đúng -> {p1:.2f}đ" + (f" (Sai: {', '.join(p1_wrong)})" if p1_wrong else " (100%)")
    s["details_p2"] = f"C13: {c13_ok}/4 ({c13_pts:.2f}đ), C14: {c14_ok}/4 ({c14_pts:.2f}đ) -> {p2:.2f}đ"
    s["details_p3"] = f"{p3_ok}/4 đúng -> {p3:.2f}đ" + (f" (Sai: {', '.join(p3_wrong)})" if p3_wrong else " (100%)")
    s["details_p4"] = f"C19: {c19:.2f}đ | C20: {c20:.2f}đ | C21: {c21:.2f}đ -> {p4:.2f}đ"

    err_parts = []
    if p1_wrong:
        err_parts.append("P1 sai " + ", ".join(p1_wrong))
    if p2_wrong:
        err_parts.append("P2 sai " + ", ".join(p2_wrong))
    if p3_wrong:
        err_parts.append("P3 sai " + ", ".join(p3_wrong))
    if s.get("p3_discrepancy_note"):
        err_parts.append(s["p3_discrepancy_note"])
    for q in ["C19", "C20", "C21"]:
        en = p4_det[q].get("error_note", "").strip()
        sc = p4_det[q]["score"]
        if en:
            err_parts.append(f"{q} ({sc:.2f}đ): {en}")
    s["errors"] = "; ".join(err_parts) if err_parts else "Không có lỗi sai."
    s["note"] = f"{rank} {total:.2f}/10.0đ (TN: {total_tn:.2f}/7.00đ, TL: {p4:.2f}/3.00đ)."
    return s


